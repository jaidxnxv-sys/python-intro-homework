# 15, 16, 6, 14, 25, 30, 7, 26
num = [6, 7, 14, 15, 16, 25, 26, 30]

#index [0]
first_item = num[0]
print("the first item is: ",first_item)

#index [7]
last_item = num[-1]
print("the last item is: ",last_item)

#slice middle [4]
middle_four = num[2:6]
print(middle_four)

#reverse list slicing
print(num[::-1])


